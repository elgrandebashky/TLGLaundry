
import os
import sqlite3
import sys

import psycopg2

SOURCE_DB = "pythonanywhere_laundry_backup.db"


def main():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        print("Greška: DATABASE_URL nije postavljen.")
        sys.exit(1)

    if not os.path.isfile(SOURCE_DB):
        print(f"Greška: Ne postoji fajl {SOURCE_DB}")
        sys.exit(1)

    source = sqlite3.connect(SOURCE_DB)
    source.row_factory = sqlite3.Row

    try:
        users = source.execute(
            'SELECT id, username, password FROM "user" ORDER BY id'
        ).fetchall()

        bookings = source.execute(
            "SELECT id, user_id, time_slot, date "
            "FROM booking ORDER BY id"
        ).fetchall()
    finally:
        source.close()

    if len(users) != 5 or len(bookings) != 10:
        print(
            f"Greška: pronađeno je {len(users)} korisnika "
            f"i {len(bookings)} rezervacija; očekivano je 5 i 10."
        )
        sys.exit(1)

    user_ids = {user["id"] for user in users}
    if any(b["user_id"] not in user_ids for b in bookings):
        print("Greška: neka rezervacija nema odgovarajućeg korisnika.")
        sys.exit(1)

    try:
        with psycopg2.connect(database_url) as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS "user" (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(150) UNIQUE NOT NULL,
                        password VARCHAR(150) NOT NULL
                    )
                """)

                cur.execute("""
                    CREATE TABLE IF NOT EXISTS booking (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id INTEGER NOT NULL REFERENCES "user"(id),
                        time_slot VARCHAR(50) NOT NULL,
                        date VARCHAR(50) NOT NULL
                    )
                """)

                cur.execute('SELECT COUNT(*) FROM "user"')
                existing_users = cur.fetchone()[0]
                cur.execute("SELECT COUNT(*) FROM booking")
                existing_bookings = cur.fetchone()[0]

                if existing_users or existing_bookings:
                    raise RuntimeError(
                        "Neon već sadrži korisnike ili rezervacije. "
                        "Podaci nisu prepisani."
                    )

                cur.executemany(
                    'INSERT INTO "user" (id, username, password) '
                    'VALUES (%s, %s, %s)',
                    [(u["id"], u["username"], u["password"]) for u in users],
                )

                cur.executemany(
                    "INSERT INTO booking (id, user_id, time_slot, date) "
                    "VALUES (%s, %s, %s, %s)",
                    [
                        (b["id"], b["user_id"], b["time_slot"], b["date"])
                        for b in bookings
                    ],
                )

                cur.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('"user"', 'id'),
                        (SELECT MAX(id) FROM "user")
                    )
                """)
                cur.execute("""
                    SELECT setval(
                        pg_get_serial_sequence('booking', 'id'),
                        (SELECT MAX(id) FROM booking)
                    )
                """)

                cur.execute('SELECT COUNT(*) FROM "user"')
                final_users = cur.fetchone()[0]
                cur.execute("SELECT COUNT(*) FROM booking")
                final_bookings = cur.fetchone()[0]

                if final_users != 5 or final_bookings != 10:
                    raise RuntimeError("Broj prenetih zapisa nije očekivan.")

        print("Migracija je uspešna!")
        print(f"Korisnici preneti: {final_users}")
        print(f"Rezervacije prenete: {final_bookings}")

    except Exception as exc:
        print("Migracija nije završena:", exc)
        sys.exit(1)


if __name__ == "__main__":
    main()
